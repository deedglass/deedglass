#!/usr/bin/env node
// postbuild.mjs: the last step of `npm run build` (S33 §3.6).
//   1. Copy buttons copy commands only: in a shell block written as "$ command" + expected output,
//      the copied text is the commands without "$ " (Expressive Code's data-code, lines split by U+007F).
//   2. dist/_headers: the security headers, with a sha256 for every inline script Starlight and
//      Astro emit (never 'unsafe-inline' for scripts). Styles keep 'unsafe-inline' (Expressive Code
//      colours tokens with style attributes).
//   3. dist/_redirects: /errors → /errors/, the docs.deedglass.com paths the product already prints
//      (doctor, scan, connectors, undo, …), and the old docs/*.md names.
//   4. Strips the sitemap's lastmod, so two builds are byte-identical.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { IMPORTS, MOVED } from './sync-docs.mjs';

const site = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const dist = join(site, 'dist');

export function* walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const encode = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** "$ cmd\x7foutput\x7f$ cmd2" → "cmd\x7fcmd2"; text without "$ " lines is left alone. */
export function commandsOnly(code) {
  const lines = code.split('\x7f');
  if (!lines.some((l) => l.startsWith('$ '))) return code;
  return lines.filter((l) => l.startsWith('$ ')).map((l) => l.slice(2)).join('\x7f');
}

