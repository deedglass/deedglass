import { PAGE_MARK, SITE, fullNote, inFull, inSmall, notInSitemap, walkFiles } from './seo.mjs';

const site = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const dist = join(site, 'dist');

export function* walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const encode = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** "$ cmd\x7foutput\x7f$ cmd2" → "cmd\x7fcmd2"; text without "$ " lines is left alone. */
export function commandsOnly(code) {
  const lines = code.split('\x7f');
  if (!lines.some((l) => l.startsWith('$ '))) return code;
  return lines.filter((l) => l.startsWith('$ ')).map((l) => l.slice(2)).join('\x7f');
}

