export function redirectsFile() {
  const lines = ['# Generated by scripts/postbuild.mjs. Paths the product prints, then the old docs/*.md names.'];
  for (const [from, to] of REDIRECTS) lines.push(`${from} ${to} 301`);
  for (const [src, slug] of Object.entries({ ...IMPORTS, ...MOVED })) {
    const name = src.replace(/^docs\//, '').replace(/\.md$/, '');
    lines.push(`/docs/${name}.md /${slug}/ 301`);
  }
  return lines.join('\n') + '\n';
}

export function headersFile(hashes) {
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.map((h) => `'sha256-${h}'`).join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'none'",
  ].join('; ');
  return [
    '# Generated by scripts/postbuild.mjs (S33 §3.6). Cloudflare Pages reads this file.',
    '/*',
    `  Content-Security-Policy: ${csp}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=()',
    '  Cross-Origin-Opener-Policy: same-origin',
    '  Strict-Transport-Security: max-age=31536000',
    '/_astro/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '/.well-known/security.txt',
    '  Content-Type: text/plain; charset=utf-8',
    '  Cache-Control: public, max-age=3600',
    '',
  ].join('\n');
}

// Preload the two faces every page shows first (Inter latin, Geist Mono latin 400), so text paints
// in its final face sooner and doesn't shift (Lighthouse CLS and mobile LCP).
function preloads() {
  const files = readdirSync(join(dist, '_astro'));
  const pick = (re) => files.find((f) => re.test(f));
  return [pick(/^inter-latin-wght-normal\..*\.woff2$/), pick(/^geist-mono-latin-400-normal\..*\.woff2$/)]
    .filter(Boolean)
    .map((f) => `<link rel="preload" href="/_astro/${f}" as="font" type="font/woff2" crossorigin>`)
    .join('');
}

function main() {
  const hashes = new Set();
  const preload = preloads();
  let copies = 0;
  for (const f of walk(dist)) {
    if (f.endsWith('.html')) {
      let s = readFileSync(f, 'utf8');
      const before = s;
      if (preload && !s.includes('rel="preload" href="/_astro/inter')) s = s.replace('<head>', '<head>' + preload);
      s = s.replace(/data-code="([^"]*)"/g, (all, v) => {
        const out = encode(commandsOnly(decode(v)));
        if (out !== v) copies++;
        return `data-code="${out}"`;
      });
      for (const m of s.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
        if (/type="application\/(ld\+)?json"/.test(m[1])) continue;
        hashes.add(createHash('sha256').update(m[2], 'utf8').digest('base64'));
      }
      if (s !== before) writeFileSync(f, s);
    }
    if (f.endsWith('.xml') && f.includes('sitemap')) {
      const s = readFileSync(f, 'utf8');
      const t = s.replace(/<lastmod>[^<]*<\/lastmod>/g, '').replace(/<url><loc>[^<]*\/_kit\/<\/loc><\/url>/g, '');
      if (t !== s) writeFileSync(f, t);
    }
  }
  const sorted = [...hashes].sort();
  writeFileSync(join(dist, '_headers'), headersFile(sorted));
  writeFileSync(join(dist, '_redirects'), redirectsFile());
  console.log(`✓ postbuild · ${copies} copy buttons copy commands only · ${sorted.length} inline script hashes in the CSP · ${REDIRECTS.length} redirects + old doc names`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
