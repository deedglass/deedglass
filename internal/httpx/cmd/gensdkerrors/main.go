// Command gensdkerrors writes the API error catalog out of internal/httpx/errors.go for the SDKs
// (S32 §3.4), so the Go server, the TypeScript SDK and the Python SDK never disagree on a code:
//
//	sdk/errors.json                               every code: status, type, the SDK class, doc_url
//	sdk/python/src/deedglass/_errors_gen.py       the same, as Python
//
// The TypeScript SDK picks its class from the envelope's type (fromEnvelope); its test reads
// sdk/errors.json and checks every code lands on the class named here, as the Python test does.
// Run it from the repo root: go run ./internal/httpx/cmd/gensdkerrors. TestSDKErrorsFresh fails
// when a generated file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/deedglass/deedglass/internal/httpx"
)

func main() {
	root := flag.String("root", ".", "the repo root")
	flag.Parse()
	files, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gensdkerrors:", err)
		os.Exit(1)
	}
	for _, p := range []string{jsonPath, pyPath} {
		full := filepath.Join(*root, p)
		if old, err := os.ReadFile(full); err == nil && bytes.Equal(old, files[p]) {
			continue
		}
		if err := os.WriteFile(full, files[p], 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gensdkerrors:", err)
			os.Exit(1)
		}
		fmt.Println("wrote", p)
	}
}

const (
	jsonPath = "sdk/errors.json"
	pyPath   = "sdk/python/src/deedglass/_errors_gen.py"
)

// Class is the SDK error class an envelope of this type and code becomes (both SDKs).
func Class(t httpx.ErrType, c httpx.Code) string {
	switch t {
	case httpx.TypeAuthentication:
		return "AuthenticationError"
	case httpx.TypePermission:
		return "PermissionDeniedError"
	case httpx.TypePolicy:
		return "PolicyDeniedError"
	case httpx.TypeRateLimit:
		if c == httpx.CodeBudgetExceeded {
			return "BudgetExceededError"
		}
		return "RateLimitError"
	case httpx.TypeInvalidRequest:
		return "InvalidRequestError"
	case httpx.TypeAPI:
		return "APIError"
	}
	return "DeedglassError"
}

type entry struct {
	Code   string `json:"code"`
	Status int    `json:"status"`
	Type   string `json:"type"`
	Class  string `json:"class"`
	DocURL string `json:"doc_url"`
}

func generate() (map[string][]byte, error) {
	var es []entry
	for _, e := range httpx.Catalog() {
		es = append(es, entry{Code: string(e.Code), Status: e.Status, Type: string(e.Type), Class: Class(e.Type, e.Code), DocURL: httpx.DocURLPrefix + string(e.Code)})
	}
	doc := map[string]any{
		"object":         "sdk_error_catalog",
		"version":        1,
		"generated_from": "internal/httpx/errors.go (go run ./internal/httpx/cmd/gensdkerrors)",
		"codes":          es,
	}
	var j bytes.Buffer
	enc := json.NewEncoder(&j)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	var py bytes.Buffer
	py.WriteString("# GENERATED by `go run ./internal/httpx/cmd/gensdkerrors` from internal/httpx/errors.go. Do not edit.\n")
	py.WriteString(`"""The API error catalog: code -> (HTTP status, envelope type, SDK class)."""` + "\n\n")
	py.WriteString("from __future__ import annotations\n\n")
	py.WriteString("CODES: dict[str, tuple[int, str, str]] = {\n")
	for _, e := range es {
		fmt.Fprintf(&py, "    %q: (%d, %q, %q),\n", e.Code, e.Status, e.Type, e.Class)
	}
	py.WriteString("}\n")
	return map[string][]byte{jsonPath: j.Bytes(), pyPath: py.Bytes()}, nil
}
