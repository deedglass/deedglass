package archive_test

import (
	"bytes"
	"encoding/json"
	"io"
	"os"
	"strings"
	"testing"

	"github.com/deedglass/deedglass/internal/deed/archive"
	"github.com/deedglass/deedglass/internal/deed/deedtest"
)

// TestBundleFormatDoc keeps the worked example in spec/v1/BUNDLE_FORMAT.md equal to a real bundle.
func TestBundleFormatDoc(t *testing.T) {
	c := deedtest.NewChain(3, deedtest.ChainOpts{})
	b := build(t, c, 1, 3, deedtest.TestKey("b").Signer)
	r, err := archive.Open(bytes.NewReader(b), archive.Limits{})
	if err != nil {
		t.Fatal(err)
	}
	_, _ = io.Copy(io.Discard, r.Deeds())
	if _, _, err := r.Finish(); err != nil {
		t.Fatal(err)
	}
	var seal []byte
	rewrite(t, b, func(name string, d []byte) []byte {
		if name == archive.NameManifestSeal {
			seal = d
		}
		return d
	})
	var pretty bytes.Buffer
	_ = json.Indent(&pretty, r.ManifestBytes(), "", "  ")
	var out strings.Builder
	out.WriteString("\n`README.txt`:\n\n```\n" + string(r.README()) + "```\n\n")
	out.WriteString("`manifest.json` (stored as one canonical line; indented here):\n\n```json\n" + pretty.String() + "\n```\n\n")
	out.WriteString("`manifest.seal.json`:\n\n```json\n" + string(seal) + "\n```\n\n")
	out.WriteString("```\n$ deedglass verify " + archive.FileName(c.Org, 1, 3) + " --keys testdata/deeds/keys/test-keys.json\n" +
		"✓ 3 deeds · chain intact · 1 seal key · 2026-10-02 → 2026-10-02\n✓ Bundle manifest matches · sealed by " + deedtest.TestKey("b").ID[:11] + "…\n```\n")
	const path = "../../../spec/v1/BUNDLE_FORMAT.md"
	const begin = "<!-- example:begin (generated by internal/deed/archive; go test ./internal/deed/archive -run TestBundleFormatDoc -update) -->\n"
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	doc := string(raw)
	i, j := strings.Index(doc, begin), strings.Index(doc, "<!-- example:end -->")
	if i < 0 || j < i {
		t.Fatal("spec/v1/BUNDLE_FORMAT.md needs the example markers")
	}
	if doc[i+len(begin):j] == out.String() {
		return
	}
	if !*update {
		t.Fatal("spec/v1/BUNDLE_FORMAT.md drifted. Run: go test ./internal/deed/archive -run TestBundleFormatDoc -update")
	}
	if err := os.WriteFile(path, []byte(doc[:i+len(begin)]+out.String()+doc[j:]), 0o644); err != nil {
		t.Fatal(err)
	}
}
