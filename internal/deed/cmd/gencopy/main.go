// Command gencopy writes the deed verification copy and key lists out of Go, so the CLI and the
// browser verifier never drift (S05 §3.8):
//
//	testdata/deeds/messages.json      every code and message template (also written by the vectors)
//	web/verify/src/messages.gen.ts    the same, as TypeScript
//	web/verify/src/keys.gen.ts        the small-order keys every verifier refuses (A13) and the
//	                                  published test-key thumbprints
//	web/verify/src/sample.gen.ts      the page's "Use sample": chains/genesis-20.jsonl and the test
//	                                  key set (TEST KEYS: labelled as such on the page)
//
// Run it from the repo root: go run ./internal/deed/cmd/gencopy. It is idempotent, and
// TestGeneratedFilesFresh fails when a generated file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/deedglass/deedglass/internal/deed"
)

const header = "// GENERATED by `go run ./internal/deed/cmd/gencopy` from %s. Do not edit.\n\n"

func main() {
	root := flag.String("root", ".", "the repo root")
	flag.Parse()
	files, err := generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gencopy:", err)
		os.Exit(1)
	}
	for _, p := range sortedKeys(files) {
		full := filepath.Join(*root, p)
		if old, err := os.ReadFile(full); err == nil && bytes.Equal(old, files[p]) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "gencopy:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(full, files[p], 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gencopy:", err)
			os.Exit(1)
		}
		fmt.Println("wrote", p)
	}
}

// generate returns every generated file, keyed by its path relative to root.
func generate(root string) (map[string][]byte, error) {
	small, err := os.ReadFile(filepath.Join(root, "testdata/deeds/keys/small-order-keys.json"))
	if err != nil {
		return nil, err
	}
	keysTS, err := keysTS(small)
	if err != nil {
		return nil, err
	}
	deeds, err := os.ReadFile(filepath.Join(root, "testdata/deeds/chains/genesis-20.jsonl"))
	if err != nil {
		return nil, err
	}
	testKeys, err := os.ReadFile(filepath.Join(root, "testdata/deeds/keys/test-keys.json"))
	if err != nil {
		return nil, err
	}
	var sample bytes.Buffer
	fmt.Fprintf(&sample, header, "testdata/deeds/chains/genesis-20.jsonl and testdata/deeds/keys/test-keys.json")
	sample.WriteString("/** Twenty deeds of one test org: key a seals 1–10, key b seals 11–20. TEST KEYS ONLY. */\n")
	fmt.Fprintf(&sample, "export const SAMPLE_DEEDS = %s;\n\n", q(string(deeds)))
	sample.WriteString("/** The published test key set. A deed it checks means nothing outside tests. */\n")
	fmt.Fprintf(&sample, "export const SAMPLE_KEYS = %s;\n", q(string(testKeys)))
	return map[string][]byte{
		"testdata/deeds/messages.json":   deed.MessageCatalogJSON(),
		"web/verify/src/messages.gen.ts": messagesTS(),
		"web/verify/src/keys.gen.ts":     keysTS,
		"web/verify/src/sample.gen.ts":   sample.Bytes(),
	}, nil
}

func messagesTS() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, "internal/deed/messages.go and errors.go")
	b.WriteString("/** Every verification code, in the order DEED_SPEC.md §11 documents them. */\n")
	b.WriteString("export const CODES = [\n")
	for _, c := range deed.Codes {
		fmt.Fprintf(&b, "  %s,\n", q(string(c)))
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type VerifyCode = (typeof CODES)[number];\n\n")
	b.WriteString("export interface MessageTemplate {\n  readonly sentence: string;\n  readonly next: string;\n}\n\n")
	b.WriteString("/** Message templates keyed by code (or code.variant); see renderMessage in report.ts. */\n")
	b.WriteString("export const MESSAGES: Readonly<Record<string, MessageTemplate>> = {\n")
	for _, k := range sortedKeys(deed.Messages) {
		m := deed.Messages[k]
		fmt.Fprintf(&b, "  %s: {\n    sentence: %s,\n    next: %s,\n  },\n", q(k), q(m.Sentence), q(m.Next))
	}
	b.WriteString("};\n")
	return b.Bytes()
}

func keysTS(smallJSON []byte) ([]byte, error) {
	var small struct {
		Data []struct {
			Name      string `json:"name"`
			PublicKey string `json:"public_key"`
			Hex       string `json:"hex"`
			Refused   string `json:"refused"`
		} `json:"data"`
	}
	if err := json.Unmarshal(smallJSON, &small); err != nil {
		return nil, fmt.Errorf("small-order-keys.json: %w", err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, header, "testdata/deeds/keys/small-order-keys.json and internal/deed/testkeys.go")
	b.WriteString("/** Ed25519 public key encodings every verifier must refuse (attack case A13). */\n")
	b.WriteString("export const SMALL_ORDER_KEYS: readonly { name: string; hex: string; refused: string }[] = [\n")
	for _, k := range small.Data {
		fmt.Fprintf(&b, "  { name: %s, hex: %s, refused: %s },\n", q(k.Name), q(k.Hex), q(k.Refused))
	}
	b.WriteString("];\n\n")
	b.WriteString("/** Thumbprints of the published test-vector seal keys: a deed they sealed means nothing outside tests. */\n")
	b.WriteString("export const TEST_KEY_THUMBPRINTS: readonly string[] = [\n")
	for _, tp := range deed.TestKeyThumbprints() {
		fmt.Fprintf(&b, "  %s,\n", q(tp))
	}
	b.WriteString("];\n")
	return b.Bytes(), nil
}

// q is a TypeScript string literal (JSON string syntax is valid TypeScript).
func q(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
