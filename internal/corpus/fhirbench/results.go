package fhirbench

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/deedglass/deedglass/internal/corpus/bench"
)

// ServerInfo describes a FHIR server in the results file.
type ServerInfo struct {
	Name     string `json:"name"`
	Version  string `json:"version"`
	Postgres string `json:"postgres"`
	Image    string `json:"image"`
}

// ScenarioInfo is one scenario on one server in the results file.
type ScenarioInfo struct {
	ID        string `json:"id"`
	Server    string `json:"server"`
	Title     string `json:"title"`
	Claim     string `json:"agent_reports"`
	Ungated   string `json:"stored_without_a_gateway"`
	Diverges  bool   `json:"diverges"`
	Behaviour string `json:"behaviour"`
}

// File is the results file (corpus/fhir/results/latest.json).
type File struct {
	Object    string         `json:"object"` // "fhir_bench_run"
	Version   int            `json:"version"`
	StartedAt string         `json:"started_at"`
	Commit    string         `json:"commit"`
	Method    string         `json:"method"` // corpus/fhir/BENCHMARK.md
	Servers   []ServerInfo   `json:"servers"`
	Subjects  []bench.Info   `json:"subjects"`
	Scenarios []ScenarioInfo `json:"scenarios"`
	Results   []*Result      `json:"results"`
	Totals    []bench.Totals `json:"totals"`
}

// Describe fills a ScenarioInfo from a scenario's expected facts on a server.
func Describe(s *Scenario, server string) ScenarioInfo {
	e := s.Expected[server]
	return ScenarioInfo{ID: s.ID, Server: server, Title: s.Title, Claim: s.AgentReports.Effect.String(), Ungated: e.Facts.String(),
		Diverges: !Equal(s.AgentReports.Effect, e.Facts), Behaviour: s.Behaviour}
}

// Tally adds up each subject's scores, in the order of subjects.
func Tally(subjects []bench.Info, rs []*Result) []bench.Totals {
	var out []bench.Totals
	for _, sub := range subjects {
		t := bench.Totals{Subject: sub.Name}
		for _, r := range rs {
			if r.Subject != sub.Name {
				continue
			}
			t.Scenarios++
			s := r.Score
			if s.Diverges {
				t.Diverging++
				switch {
				case s.Caught && s.Flag == bench.FlagBefore:
					t.Caught++
					t.CaughtBefore++
				case s.Caught:
					t.Caught++
					t.CaughtAfter++
				default:
					t.Missed++
					if s.Flag == bench.FlagUnverifiable {
						t.Unverifiable++
					}
				}
			}
			if s.FalseAlarm {
				t.FalseAlarms++
			}
			if s.Effect {
				t.Effect++
			}
			if s.Record {
				t.Record++
			}
		}
		out = append(out, t)
	}
	return out
}

// Write writes the file, indented, with a trailing newline.
func (f *File) Write(path string) error {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(f); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

// Read reads a results file.
func Read(path string) (*File, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var f File
	if err := json.Unmarshal(b, &f); err != nil {
		return nil, err
	}
	return &f, nil
}

func (f *File) result(subject, id, server string) *Result {
	for _, r := range f.Results {
		if r.Subject == subject && r.Scenario == id && r.Server == server {
			return r
		}
	}
	return nil
}

func cell(r *Result) string {
	if r == nil {
		return "not run"
	}
	s := r.Score
	var caught string
	switch {
	case s.Caught && s.Flag == bench.FlagBefore:
		caught = "caught before the write"
	case s.Caught:
		caught = "caught after the write"
	case s.FalseAlarm:
		caught = "false alarm"
	case s.Diverges && s.Flag == bench.FlagUnverifiable:
		caught = "**missed** (said it can't tell)"
	case s.Diverges:
		caught = "**missed**"
	default:
		caught = "nothing to catch, no flag"
	}
	yn := func(b bool) string {
		if b {
			return "yes"
		}
		return "no"
	}
	return fmt.Sprintf("%s · effect %s · record %s", caught, yn(s.Effect), yn(s.Record))
}

// Markdown is the results table: one row per scenario and server, one column per subject, then
// the totals, the subjects and what each one said.
func (f *File) Markdown() string {
	var b strings.Builder
	b.WriteString("# FHIR write-integrity benchmark results\n\n")
	var srv []string
	for _, s := range f.Servers {
		srv = append(srv, fmt.Sprintf("%s %s on PostgreSQL %s", s.Name, s.Version, s.Postgres))
	}
	fmt.Fprintf(&b, "Run %s at commit `%s` on %s. Synthetic data only. Generated by `make fhir-bench` from `corpus/fhir/results/latest.json`; the method is [`corpus/fhir/BENCHMARK.md`](../BENCHMARK.md). Do not edit by hand.\n\n",
		f.StartedAt, short(f.Commit), strings.Join(srv, ", "))
	b.WriteString("| Scenario | Server | The agent reports | Stored without a gateway |")
	for _, s := range f.Subjects {
		fmt.Fprintf(&b, " %s |", s.Name)
	}
	b.WriteString("\n|---|---|---|---|")
	for range f.Subjects {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, sc := range f.Scenarios {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |", sc.ID, sc.Server, sc.Claim, sc.Ungated)
		for _, sub := range f.Subjects {
			fmt.Fprintf(&b, " %s |", cell(f.result(sub.Name, sc.ID, sc.Server)))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n| Totals |")
	for _, s := range f.Subjects {
		fmt.Fprintf(&b, " %s |", s.Name)
	}
	b.WriteString("\n|---|")
	for range f.Subjects {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	rows := []struct {
		name string
		v    func(bench.Totals) string
	}{
		{"Caught (of the scenarios where the report and what was stored differ)", func(t bench.Totals) string { return fmt.Sprintf("%d of %d", t.Caught, t.Diverging) }},
		{"before the write", func(t bench.Totals) string { return fmt.Sprint(t.CaughtBefore) }},
		{"after the write", func(t bench.Totals) string { return fmt.Sprint(t.CaughtAfter) }},
		{"Missed", func(t bench.Totals) string { return fmt.Sprint(t.Missed) }},
		{"of which it said it can't tell (UNVERIFIABLE)", func(t bench.Totals) string { return fmt.Sprint(t.Unverifiable) }},
		{"False alarms", func(t bench.Totals) string { return fmt.Sprint(t.FalseAlarms) }},
		{"Reported the true effect", func(t bench.Totals) string { return fmt.Sprintf("%d of %d", t.Effect, t.Scenarios) }},
		{"Left a record a third party can check", func(t bench.Totals) string { return fmt.Sprintf("%d of %d", t.Record, t.Scenarios) }},
	}
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s |", r.name)
		for _, t := range f.Totals {
			fmt.Fprintf(&b, " %s |", r.v(t))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n## Subjects\n\n")
	for _, s := range f.Subjects {
		v := ""
		if s.Version != "" {
			v = " " + s.Version
		}
		fmt.Fprintf(&b, "- **%s**%s (%s): %s\n", s.Name, v, s.Kind, s.Config)
	}
	b.WriteString("\n## What each subject said\n\n")
	for _, sc := range f.Scenarios {
		fmt.Fprintf(&b, "### `%s` on %s: %s\n\n%s\n\n", sc.ID, sc.Server, sc.Title, sc.Behaviour)
		for _, sub := range f.Subjects {
			r := f.result(sub.Name, sc.ID, sc.Server)
			if r == nil {
				continue
			}
			eff := "doesn't say"
			if r.Report.Effect != nil {
				eff = r.Report.Effect.String()
			}
			fmt.Fprintf(&b, "- **%s**: stored %s; it says %s. %s\n", sub.Name, r.Stored.String(), eff, strings.Join(r.Report.Notes, "; "))
			if r.Report.Record != nil && !r.Report.Record.Checked {
				fmt.Fprintf(&b, "  Record not checked: %s\n", r.Report.Record.Problem)
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

func short(c string) string {
	if len(c) > 12 {
		return c[:12]
	}
	return c
}
