export function plainVerdict(v: string): string {
  return ({ VERIFIED: copy.chips.verified, MISMATCH: copy.chips.mismatch, UNVERIFIABLE: copy.chips.unverifiable } as Record<string, string>)[v] ?? v;
}

/** plainLevel: a level's plain name (Claimed, Checked, Proven). Unknown values come back as written. */
export function plainLevel(l: string): string {
  return copy.chips.level[l] ?? l;
}

