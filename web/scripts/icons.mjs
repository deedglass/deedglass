// lucide-static (build time only) + src/icons/custom/*.svg → public/icons.svg (one sprite of
// <symbol id="i-name">) and src/icons/names.gen.ts (S24 §3.5). Only the names in src/icons/used.json
// ship; a missing name fails the build, and test/icons.test.ts fails on unused names.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const names = JSON.parse(readFileSync(root + 'src/icons/used.json', 'utf8'));
const check = process.argv.includes('--check');

function inner(svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return body.replace(/\s*\n\s*/g, '').trim();
}

const symbols = [];
for (const n of [...names].sort()) {
  const custom = root + `src/icons/custom/${n}.svg`;
  const lucide = root + `node_modules/lucide-static/icons/${n}.svg`;
  const file = existsSync(custom) ? custom : lucide;
  if (!existsSync(file)) {
    console.error(`icons: ${n} is in used.json but is neither a custom icon nor in lucide-static`);
    process.exit(1);
  }
  symbols.push(`<symbol id="i-${n}" viewBox="0 0 24 24">${inner(readFileSync(file, 'utf8'))}</symbol>`);
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide (ISC) and Deedglass custom icons: generated by web/scripts/icons.mjs -->\n${symbols.join('\n')}\n</svg>\n`;
const ts = `// generated by web/scripts/icons.mjs from src/icons/used.json. Do not edit.\n\nexport const iconNames = ${JSON.stringify([...names].sort())} as const;\nexport type IconName = (typeof iconNames)[number];\n`;
const outputs = [[root + 'public/icons.svg', sprite], [root + 'src/icons/names.gen.ts', ts]];
let stale = 0;
for (const [p, body] of outputs) {
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (cur === body) continue;
  if (check) { console.error(`stale: ${p.replace(root, 'web/')}`); stale++; } else { writeFileSync(p, body); console.log(`wrote ${p.replace(root, 'web/')} (${names.length} icons)`); }
}
if (stale) process.exit(1);
