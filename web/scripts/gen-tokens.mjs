// tokens/tokens.json → src/styles/tokens.css, src/lib/tokens.gen.ts, src/lib/contrast.gen.ts and the
// /* tokens:begin */…/* tokens:end */ block of web/verify/src/ui/styles.css (S24 §3.2).
// `--check` writes nothing and exits 1 when any output is stale (make web-test runs it).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadTokens, table } from './contrast.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const t = loadTokens();
const HEADER = 'generated by web/scripts/gen-tokens.mjs from web/tokens/tokens.json. Do not edit; run make web-tokens.';

const lower = (v) => (/^#[0-9A-F]+$/i.test(v) ? v.toLowerCase() : v);
const value = (theme, v) => {
  if (v in t.primitives) return `var(--${v})`;
  if (v in t.themes[theme]) return `var(--${v})`;
  return lower(v);
};

function css() {
  const out = [`/* ${HEADER} */`, '', ':root {'];
  out.push('  /* primitives (brand §6): role variables below point at these */');
  for (const [k, v] of Object.entries(t.primitives)) out.push(`  --${k}: ${lower(v)};`);
  out.push('', '  /* type (S24 §3.3) */');
  out.push(`  --font-sans: ${t.fonts.sans};`, `  --font-mono: ${t.fonts.mono};`);
  for (const [k, v] of Object.entries(t.typography)) {
    out.push(`  --type-${k}-size: ${v.size};`, `  --type-${k}-line: ${v.line};`, `  --type-${k}-weight: ${v.weight};`, `  --type-${k}-tracking: ${v.tracking};`);
  }
  out.push('', '  /* space, radius, size */');
  for (const [k, v] of Object.entries(t.space)) out.push(`  --space-${String(k).replace('.', '_')}: ${v};`);
  for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.size)) out.push(`  --size-${k}: ${v};`);
  out.push('', '  /* motion (brand §10) */');
  for (const [k, v] of Object.entries(t.motion)) out.push(`  --${k.startsWith('ease') ? k : 'dur-' + k}: ${v};`);
  out.push('', '  /* z-order */');
  for (const [k, v] of Object.entries(t.z)) out.push(`  --z-${k}: ${v};`);
  out.push('}', '');
  const roles = (theme, indent) => Object.entries(t.themes[theme]).map(([k, v]) => `${indent}--${k}: ${value(theme, v)};`);
  out.push('/* Dark is the default (brand §13.1): no attribute, or data-theme="dark". */');
  out.push(':root,', ':root[data-theme="dark"] {', '  color-scheme: dark;', ...roles('dark', '  '), '}', '');
  out.push(':root[data-theme="light"] {', '  color-scheme: light;', ...roles('light', '  '), '}', '');
  out.push('@media (prefers-color-scheme: light) {', '  :root[data-theme="system"] {', '    color-scheme: light;', ...roles('light', '    '), '  }', '}', '');
  return out.join('\n');
}

function ts() {
  const motion = Object.fromEntries(Object.entries(t.motion).filter(([k]) => !k.startsWith('ease')).map(([k, v]) => [k, parseInt(v, 10)]));
  const bp = Object.fromEntries(Object.entries(t.breakpoints).map(([k, v]) => [k, parseInt(v, 10)]));
  return `// ${HEADER}\n\nexport const motion = ${JSON.stringify(motion)} as const;\n` +
    `export const easeEnter = ${JSON.stringify(t.motion['ease-enter'])};\nexport const easeExit = ${JSON.stringify(t.motion['ease-exit'])};\n` +
    `export const breakpoints = ${JSON.stringify(bp)} as const;\n`;
}

function contrastTs() {
  const { rows, findings } = table(t);
  return `// ${HEADER}\n\nexport interface ContrastRow { theme: string; fg: string; bg: string; kind: string; note: string; ratio: number; need: number; pass: boolean }\n` +
    `export const contrastRows: ContrastRow[] = ${JSON.stringify(rows, null, 1)};\n` +
    `export const contrastFindings: { label: string; ratio: number; decision: string }[] = ${JSON.stringify(findings.map(({ label, ratio, decision }) => ({ label, ratio, decision })), null, 1)};\n`;
}

// The verify page keeps its own role variables; it takes the primitives, motion, shape and fonts.
function verifyBlock() {
  const p = t.primitives;
  const names = ['ink-950', 'ink-900', 'ink-850', 'ink-800', 'ink-700', 'slate-500', 'slate-400', 'slate-300', 'mist-100', 'paper-50', 'white', 'ink-text', 'snow-text'];
  const lines = ['/* tokens:begin */', `  /* ${HEADER} */`, '  /* neutrals (brand §6.1) */'];
  for (const n of names) lines.push(`  --${n}: ${lower(p[n])};`);
  lines.push('  /* aurora (brand §6.2): the mark only */');
  for (const n of ['aurora-violet', 'aurora-blue', 'aurora-teal']) lines.push(`  --${n}: ${lower(p[n])};`);
  lines.push('  /* motion (brand §10) */', `  --ease-enter: ${t.motion['ease-enter']};`, `  --ease-exit: ${t.motion['ease-exit']};`,
    `  --dur-micro: ${t.motion.micro};`, `  --dur-component: ${t.motion.component};`, `  --dur-sheet: ${t.motion.sheet};`, `  --dur-page: ${t.motion.reveal};`,
    '  /* shape (brand §8) */', `  --radius-chip: ${t.radius.chip};`, `  --radius-button: ${t.radius.button};`, `  --radius-card: ${t.radius.card};`,
    `  --font-sans: ${t.fonts.sans};`, `  --font-mono: ${t.fonts.mono};`, '  /* tokens:end */');
  return lines.join('\n');
}

// The favicon: the flat Split Orb (brand §5), colours from the primitives.
function favicon() {
  const p = t.primitives;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120"><defs><linearGradient id="a" x1="0" y1="0" x2="1" y2="1">` +
    `<stop offset="0" stop-color="${lower(p['aurora-violet'])}"/><stop offset=".5" stop-color="${lower(p['aurora-blue'])}"/><stop offset="1" stop-color="${lower(p['aurora-teal'])}"/></linearGradient></defs>` +
    `<path d="M55.2 8.22A52 52 0 0 0 55.2 111.78Z" fill="url(#a)"/><path d="M64.8 8.22A52 52 0 0 1 64.8 111.78Z" fill="${lower(p['frost-dark'])}" fill-opacity=".85"/></svg>\n`;
}

const outputs = [
  [root + 'public/favicon.svg', favicon()],
  [root + 'src/styles/tokens.css', css()],
  [root + 'src/lib/tokens.gen.ts', ts()],
  [root + 'src/lib/contrast.gen.ts', contrastTs()],
];
// docs/DESIGN_SYSTEM.md: the token tables between <!-- tokens:begin --> and <!-- tokens:end -->.
function docTables() {
  const md = ['<!-- tokens:begin -->', `<!-- ${HEADER} -->`, '', '### Roles (dark is the default)', '', '| Role | Dark | Light |', '|---|---|---|'];
  const res = (theme, v) => {
    let x = v;
    for (let i = 0; i < 4 && t.themes[theme][x]; i++) x = t.themes[theme][x];
    return t.primitives[x] ? `\`${x}\` ${t.primitives[x]}` : `\`${x}\``;
  };
  for (const k of Object.keys(t.themes.dark)) md.push(`| \`--${k}\` | ${res('dark', t.themes.dark[k])} | ${res('light', t.themes.light[k])} |`);
  md.push('', '### Type', '', '| Token | Size / line | Weight | Tracking |', '|---|---|---|---|');
  for (const [k, v] of Object.entries(t.typography)) md.push(`| \`${k}\` | ${v.size} / ${v.line} | ${v.weight} | ${v.tracking} |`);
  md.push('', '### Space, radius, size, motion, z', '');
  md.push('Space: ' + Object.values(t.space).join(' · ') + '.');
  md.push('', 'Radius: ' + Object.entries(t.radius).map(([k, v]) => `${k} ${v}`).join(' · ') + '.');
  md.push('', 'Size: ' + Object.entries(t.size).map(([k, v]) => `${k} ${v}`).join(' · ') + '.');
  md.push('', 'Breakpoints: ' + Object.entries(t.breakpoints).map(([k, v]) => `${k} ${v}`).join(' · ') + '.');
  md.push('', 'Motion: ' + Object.entries(t.motion).map(([k, v]) => `${k} ${v}`).join(' · ') + '.');
  md.push('', 'Z-order: ' + Object.entries(t.z).map(([k, v]) => `${k} ${v}`).join(' · ') + '.');
  const { rows } = table(t);
  md.push('', '### Contrast (generated by contrast.mjs)', '', '| Theme | Foreground | Background | Kind | Ratio | Result |', '|---|---|---|---|---|---|');
  for (const r of rows) md.push(`| ${r.theme} | \`${r.fg}\` | \`${r.bg}\` | ${r.kind} | ${r.ratio.toFixed(2)} | ${r.kind === 'decorative' ? 'decorative' : r.pass ? `pass (${r.need}:1)` : `FAIL (${r.need}:1)`} |`);
  md.push('<!-- tokens:end -->');
  return md.join('\n');
}
const docPath = root + '../docs/DESIGN_SYSTEM.md';
const docMD = readFileSync(docPath, 'utf8');
const docRE = /<!-- tokens:begin -->[\s\S]*?<!-- tokens:end -->/;
if (!docRE.test(docMD)) {
  console.error('gen-tokens: docs/DESIGN_SYSTEM.md has no <!-- tokens:begin --> … <!-- tokens:end --> block');
  process.exit(1);
}
outputs.push([docPath, docMD.replace(docRE, docTables())]);

const verifyPath = root + 'verify/src/ui/styles.css';
const verifyCSS = readFileSync(verifyPath, 'utf8');
const re = /\/\* tokens:begin \*\/[\s\S]*?\/\* tokens:end \*\//;
if (!re.test(verifyCSS)) {
  console.error('gen-tokens: web/verify/src/ui/styles.css has no /* tokens:begin */ … /* tokens:end */ block');
  process.exit(1);
}
outputs.push([verifyPath, verifyCSS.replace(re, verifyBlock().replace(/^ {2}/, ''))]);

let stale = 0;
for (const [path, body] of outputs) {
  let cur = '';
  try { cur = readFileSync(path, 'utf8'); } catch { /* new file */ }
  if (cur === body) continue;
  if (check) {
    console.error(`stale: ${path.replace(root, 'web/')} (run make web-tokens)`);
    stale++;
  } else {
    writeFileSync(path, body);
    console.log(`wrote ${path.replace(root, 'web/')}`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log('tokens: every generated file is current');
}
