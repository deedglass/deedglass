package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"sort"
	"strings"
)

// Shell completions (S35, contract §10): `deedglass completion zsh|bash|fish` prints a script
// generated from the same command table help and `help --json` read, so a new command or flag is
// completed the moment it is registered. The scripts are static: they never run deedglass while
// completing, and they carry no version, so the release's completions/ files are reproducible.

// complNode is one word of the command tree: its summary and the words that may follow it.
type complNode struct {
	path    string // "agent keys"
	summary string
	subs    []string
	flags   []complFlag // only on runnable leaves
}

// dash is how the flag is typed: -v, --json.
func (f complFlag) dash() string {
	if len(f.name) == 1 {
		return "-" + f.name
	}
	return "--" + f.name
}

type complFlag struct {
	name, usage string
	bool        bool
	values      []string
}

var globalComplFlags = []complFlag{
	{name: "json", usage: "print JSON", bool: true},
	{name: "server", usage: "the Deedglass server URL"},
	{name: "api-key", usage: "an API key (else DEEDGLASS_API_KEY)"},
	{name: "org", usage: "the org, for operator commands"},
	{name: "no-color", usage: "no colour", bool: true},
	{name: "v", usage: "more detail", bool: true},
}

// complTree builds the tree of built, visible commands. Group summaries come from help's lines.
func complTree() map[string]*complNode {
	nodes := map[string]*complNode{"": {path: ""}}
	lineSummary := map[string]string{}
	for _, l := range lines {
		lineSummary[l.Name] = l.Summary
	}
	for _, c := range commands {
		if !c.Built() || (c.Hidden && c.Path[0] != "help") {
			continue
		}
		for i := range c.Path {
			parent, key := strings.Join(c.Path[:i], " "), strings.Join(c.Path[:i+1], " ")
			n, ok := nodes[key]
			if !ok {
				n = &complNode{path: key, summary: lineSummary[key]}
				nodes[key] = n
				nodes[parent].subs = append(nodes[parent].subs, c.Path[i])
			}
			if i == len(c.Path)-1 {
				n.summary = c.Summary
				if c.Flags != nil {
					fs := flag.NewFlagSet(key, flag.ContinueOnError)
					c.Flags(fs)
					fs.VisitAll(func(f *flag.Flag) {
						n.flags = append(n.flags, complFlag{name: f.Name, usage: firstLine(f.Usage), bool: flagType(f) == "bool",
							values: flagValues[key+" --"+f.Name]})
					})
				}
			}
		}
	}
	for _, n := range nodes {
		if n.summary == "" {
			n.summary = "Commands for " + n.path
		}
	}
	return nodes
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	return s
}

func complKeys(m map[string]*complNode) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// The completion rows' Run is set here, not in the table: the generator reads the table.
func init() {
	for _, c := range commands {
		if len(c.Path) == 2 && c.Path[0] == "completion" {
			c.Run = runCompletion(c.Path[1])
		}
	}
}

func runCompletion(shell string) func(context.Context, *Env, []string) error {
	return func(_ context.Context, e *Env, args []string) error {
		if len(args) > 0 {
			return usageErr(fmt.Errorf("deedglass completion %s takes no arguments (got %q)", shell, args[0]),
				"Run deedglass completion "+shell+" > <file>; deedglass help completion "+shell+" shows where the file goes.")
		}
		return writeCompletion(e.Stdout, shell)
	}
}

func writeCompletion(w io.Writer, shell string) error {
	nodes := complTree()
	switch shell {
	case "bash":
		return bashCompletion(w, nodes)
	case "zsh":
		return zshCompletion(w, nodes)
	case "fish":
		return fishCompletion(w, nodes)
	}
	return fmt.Errorf("unknown shell %q", shell)
}

// shSingle quotes s for sh, bash, zsh and fish single quotes.
func shSingle(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

func fishSingle(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, "'", `\'`).Replace(s) + "'"
}

// knownPaths is "|init|agent|agent create|…|", the membership string the bash and zsh scripts
// use to tell a command word from a flag's value.
func knownPaths(nodes map[string]*complNode) string {
	var b strings.Builder
	b.WriteString("|")
	for _, k := range complKeys(nodes) {
		if k != "" {
			b.WriteString(k + "|")
		}
	}
	return b.String()
}

func valueFlags(nodes map[string]*complNode, k string) []complFlag {
	var out []complFlag
	for _, f := range nodes[k].flags {
		if len(f.values) > 0 {
			out = append(out, f)
		}
	}
	return out
}

func bashCompletion(w io.Writer, nodes map[string]*complNode) error {
	var b strings.Builder
	b.WriteString(`# bash completion for deedglass. Generated by: deedglass completion bash
# Install: deedglass completion bash > "${BASH_COMPLETION_USER_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/bash-completion}/completions/deedglass"
_deedglass() {
  local cur prev w i path="" known=` + shSingle(knownPaths(nodes)) + ` subs="" flags=""
  cur="${COMP_WORDS[COMP_CWORD]}"
  prev="${COMP_WORDS[COMP_CWORD-1]}"
  for ((i = 1; i < COMP_CWORD; i++)); do
    w="${COMP_WORDS[i]}"
    [[ $w == -* ]] && continue
    [[ $known == *"|${path:+$path }$w|"* ]] && path="${path:+$path }$w"
  done
  case "$path" in
`)
	for _, k := range complKeys(nodes) {
		n := nodes[k]
		var fl []string
		for _, f := range n.flags {
			fl = append(fl, f.dash())
		}
		if len(n.subs) == 0 && len(fl) == 0 {
			continue
		}
		fmt.Fprintf(&b, "    %s) subs=%s; flags=%s ;;\n", shSingle(k), shSingle(strings.Join(n.subs, " ")), shSingle(strings.Join(fl, " ")))
	}
	b.WriteString("  esac\n  case \"$path $prev\" in\n")
	for _, k := range complKeys(nodes) {
		for _, f := range valueFlags(nodes, k) {
			fmt.Fprintf(&b, "    %s) COMPREPLY=($(compgen -W %s -- \"$cur\")); return ;;\n", shSingle(k+" "+f.dash()), shSingle(strings.Join(f.values, " ")))
		}
	}
	var gl []string
	for _, f := range globalComplFlags {
		gl = append(gl, f.dash())
	}
	fmt.Fprintf(&b, `  esac
  if [[ $cur == -* ]]; then
    COMPREPLY=($(compgen -W "$flags %s" -- "$cur"))
  else
    COMPREPLY=($(compgen -W "$subs" -- "$cur"))
  fi
}
complete -o default -F _deedglass deedglass
`, strings.Join(gl, " "))
	_, err := io.WriteString(w, b.String())
	return err
}

func zshCompletion(w io.Writer, nodes map[string]*complNode) error {
	var b strings.Builder
	b.WriteString(`#compdef deedglass
# zsh completion for deedglass. Generated by: deedglass completion zsh
# Install: deedglass completion zsh > "${fpath[1]}/_deedglass", then start a new shell.
_deedglass() {
  local w path="" known=` + shSingle(knownPaths(nodes)) + `
  local -a subs flags
  for w in "${(@)words[2,CURRENT-1]}"; do
    [[ $w == -* ]] && continue
    [[ $known == *"|${path:+$path }$w|"* ]] && path="${path:+$path }$w"
  done
  case "$path ${words[CURRENT-1]}" in
`)
	for _, k := range complKeys(nodes) {
		for _, f := range valueFlags(nodes, k) {
			fmt.Fprintf(&b, "    %s) compadd -- %s; return ;;\n", shSingle(k+" "+f.dash()), strings.Join(f.values, " "))
		}
	}
	b.WriteString("  esac\n  case \"$path\" in\n")
	for _, k := range complKeys(nodes) {
		n := nodes[k]
		if len(n.subs) == 0 && len(n.flags) == 0 {
			continue
		}
		fmt.Fprintf(&b, "    %s)\n", shSingle(k))
		if len(n.subs) > 0 {
			b.WriteString("      subs=(")
			for _, s := range n.subs {
				child := strings.TrimSpace(k + " " + s)
				b.WriteString(" " + shSingle(s+":"+strings.ReplaceAll(nodes[child].summary, ":", `\:`)))
			}
			b.WriteString(" )\n")
		}
		if len(n.flags) > 0 {
			b.WriteString("      flags=(")
			for _, f := range n.flags {
				b.WriteString(" " + shSingle(f.dash()+":"+strings.ReplaceAll(f.usage, ":", `\:`)))
			}
			b.WriteString(" )\n")
		}
		b.WriteString("      ;;\n")
	}
	b.WriteString("  esac\n  flags+=(")
	for _, f := range globalComplFlags {
		b.WriteString(" " + shSingle(f.dash()+":"+f.usage))
	}
	b.WriteString(` )
  if [[ $PREFIX == -* ]]; then
    _describe -t flags 'flag' flags
  elif (( ${#subs} )); then
    _describe -t commands 'deedglass command' subs
  else
    _files
  fi
}
if [[ $funcstack[1] == _deedglass ]]; then
  _deedglass "$@"
else
  compdef _deedglass deedglass
fi
`)
	_, err := io.WriteString(w, b.String())
	return err
}

func fishCompletion(w io.Writer, nodes map[string]*complNode) error {
	var b strings.Builder
	b.WriteString(`# fish completion for deedglass. Generated by: deedglass completion fish
# Install: deedglass completion fish > ~/.config/fish/completions/deedglass.fish
function __deedglass_path
    set -l known ` + fishSingle(knownPaths(nodes)) + `
    set -l path ""
    for w in (commandline -opc)[2..-1]
        string match -q -- '-*' $w; and continue
        set -l next (string trim -- "$path $w")
        string match -q -- "*|$next|*" $known; and set path $next
    end
    echo $path
end
function __deedglass_is
    test (__deedglass_path) = "$argv[1]"
end
complete -c deedglass -f
`)
	for _, f := range globalComplFlags {
		if len(f.name) == 1 {
			fmt.Fprintf(&b, "complete -c deedglass -s %s -d %s\n", f.name, fishSingle(f.usage))
		} else {
			fmt.Fprintf(&b, "complete -c deedglass -l %s -d %s\n", f.name, fishSingle(f.usage))
		}
	}
	for _, k := range complKeys(nodes) {
		n := nodes[k]
		cond := fishSingle("__deedglass_is " + fishSingle(k))
		for _, s := range n.subs {
			child := strings.TrimSpace(k + " " + s)
			fmt.Fprintf(&b, "complete -c deedglass -n %s -a %s -d %s\n", cond, fishSingle(s), fishSingle(nodes[child].summary))
		}
		for _, f := range n.flags {
			opt := "-l " + f.name
			if len(f.name) == 1 {
				opt = "-s " + f.name
			}
			extra := ""
			if !f.bool {
				extra = " -r"
			}
			if len(f.values) > 0 {
				extra += " -a " + fishSingle(strings.Join(f.values, " "))
			}
			fmt.Fprintf(&b, "complete -c deedglass -n %s %s%s -d %s\n", cond, opt, extra, fishSingle(f.usage))
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}
